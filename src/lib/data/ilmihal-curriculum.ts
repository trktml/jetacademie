function makeIlmihalEntryId(
  grade: number,
  gender: Gender,
  month: number,
  week: number,
  isExtra: boolean = false,
  extraOrder?: number
): string {
  const prefix = grade === 1 ? "" : `g${grade}-`;
  if (isExtra) {
    return `${prefix}ilmihal-${gender}-extra-${extraOrder ?? 1}`;
  }
  const monthSlug = monthSlugs[month] ?? `m${month}`;
  return `${prefix}ilmihal-${gender}-${monthSlug}-${week}`;
}

