/**
 * Belirtilen sınıf (1-6) ve cinsiyet (erkek / bayan) için İlmihal müfredat girişlerini üretir.
 * - 1, 2, 3. sınıflar: Ortaokul (28 hafta)
 * - 4, 5, 6. sınıflar: Lise (Bayan: 104 hafta [48 standart + 56 ekstra], Erkek: 98 hafta [48 standart + 50 ekstra])
 */
export function getIlmihalEntriesForGrade(grade: number, gender: Gender): CurriculumEntry[] {
  let items: readonly IlmihalCurriculumItem[];
  if (grade <= 3) {
    items = gender === "bayan" ? ortaokulIlmihalBayan : ortaokulIlmihalErkek;
  } else {
    items = gender === "bayan" ? liseIlmihalBayan : liseIlmihalErkek;
  }

  return items.map((item) => {
    const level = grade <= 3 ? "ortaokul" : "lise";
    const weekPad = String(item.weekNumber).padStart(2, "0");
    const pdfUrl = `/curriculum/ilmihal/${level}/${gender}/hafta-${weekPad}.pdf`;

    if (item.weekNumber <= 48) {
      const monthIndex = Math.floor((item.weekNumber - 1) / 4); // 0..11
      const month = monthIndex < 4 ? 9 + monthIndex : monthIndex - 3;
      const year = monthIndex < 4 ? 2026 : 2027;
      const weekInMonth = ((item.weekNumber - 1) % 4) + 1;
      const id = makeIlmihalEntryId(grade, gender, month, weekInMonth, false);

      return {
        id,
        grade,
        gender,
        categoryId: "ilmihal",
        month,
        week: weekInMonth,
        year,
        isExtra: false,
        title: item.title,
        body: item.body,
        pageCount: item.pageCount,
        resourceUrl: pdfUrl,
        pdfUrl,
      };
    }

    const extraOrder = item.weekNumber - 48;
    const id = makeIlmihalEntryId(grade, gender, 8, 4, true, extraOrder);

    return {
      id,
      grade,
      gender,
      categoryId: "ilmihal",
      month: 8,
      week: 4,
      year: 2027,
      isExtra: true,
      extraOrder,
      title: item.title,
      body: item.body,
      pageCount: item.pageCount,
      resourceUrl: pdfUrl,
      pdfUrl,
    };
  });
}

/**
 * 6 Belçika sınıfı ve 2 cinsiyet için tüm İlmihal kayıtlarını döner (toplam 774 kayıt).
 */
export function getAllIlmihalEntries(): CurriculumEntry[] {
  const all: CurriculumEntry[] = [];
  for (let grade = 1; grade <= 6; grade++) {
    all.push(...getIlmihalEntriesForGrade(grade, "erkek"));
    all.push(...getIlmihalEntriesForGrade(grade, "bayan"));
  }
  return all;
}
